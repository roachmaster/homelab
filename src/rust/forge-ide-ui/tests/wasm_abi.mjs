const inspect = send({ kind: 'paired', request_id: id, catalog: { protocol_version: 1, session_epoch: 'test-session', timeout_ms: 1000, nodes: [{ key: 'lab', label: 'Lab', node: 'node', incarnation: 'boot', projects: [{ alias: 'project', label: 'Project' }] }] } });
